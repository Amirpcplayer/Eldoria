def title_for_level(level: int) -> str:
    level = max(1, min(100, int(level or 1)))
    return TITLES[level - 1]

def sync_unlocked_titles(character: Character) -> list[int]:
    """Ensure all level titles up to the current level are recorded."""
    level = max(1, min(100, int(character.level or 1)))
    existing = character.unlocked_titles or []
    normalized: set[int] = set()
    for value in existing:
        try:
            n = int(value)
            if 1 <= n <= 100:
                normalized.add(n)
        except (TypeError, ValueError):
            continue
    normalized.update(range(1, level + 1))
    character.unlocked_titles = sorted(normalized)
    if not character.active_title or character.active_title not in [TITLES[n - 1] for n in normalized]:
        character.active_title = title_for_level(level)
    return sorted(normalized)

async def persist_title_unlocks(session: AsyncSession, character: Character) -> None:
    sync_unlocked_titles(character)
    await session.flush()
