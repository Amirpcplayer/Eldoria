    ("راهزن جنگل", "راهزنی نقاب‌دار که پشت درختان پنهان شده"),
    ("اسکلت نگهبان", "اسکلتی که زره شکسته‌ای به تن دارد"),
    ("خفاش غار", "خفاشی بزرگ که از سقف غار شیرجه می‌زند"),
    ("جادوگر سرگردان", "جادوگری آواره با عصایی ترک‌خورده"),
    ("عنکبوت زهرآلود", "عنکبوتی سمی که تارش را میان راه کشیده"),
    ("شبح مه‌آلود", "شبحی لرزان که از میان مه پدیدار شده"),
