    ("در پیچ جاده صدای خش‌خش شنیدی؛ {enemy} از پشت صخره بیرون پرید.", "با واکنشی برق‌آسا کمینش را خنثی کردی."),
    ("چراغ‌های مسیر ناگهان خاموش شدند و {enemy} راهت را بست.", "ضربه‌ات تاریکی را شکافت و مهاجم را عقب راند."),
    ("ردپاهای تازه به بن‌بست می‌رسید؛ همان‌جا {enemy} به تو یورش آورد.", "مسیر حمله‌اش را خواندی و با حرکتی دقیق پیروز شدی."),
    ("صدای شکستن شاخه‌ای از بالای سرت آمد؛ {enemy} از کمین فرود آمد.", "پیش از آن‌که فرصت ضربهٔ دوم پیدا کند، حمله‌ات به هدف نشست."),
