async def _reward_contributors(session, boss: GroupBoss, last_character_id: int) -> tuple[list[tuple[int, int, str]], str]:
    rows = list((await session.execute(
        select(GroupBossContribution, Character)
        .join(Character, Character.id == GroupBossContribution.character_id)
        .where(GroupBossContribution.boss_id == boss.id)
    )).all())

    total_damage = max(
        1,
        sum(max(0, int(contribution.damage or 0)) for contribution, _ in rows),
    )
    cfg = next((b for b in BOSS_POOL if b["key"] == boss.boss_key), BOSS_POOL[0])
    level = max(1, min(200, int(getattr(boss, "boss_level", 1) or 1)))
    rewards = boss_level_stats(cfg, level)

    potions = list((await session.scalars(
        select(Item).where(Item.item_type == "potion")
    )).all())

    equipment = []
    if level >= 100:
        candidates = list((await session.scalars(
            select(Item).where(Item.item_type == "equipment")
        )).all())
        equipment = [
            item for item in candidates
            if str(getattr(item, "rarity", "") or "").strip().casefold() != "divine"
        ]

    notices = []
    report_rows = []

    async def grant_item(character, item, quantity=1):
        if item is None or quantity <= 0:
            return

        inventory = await session.scalar(
            select(Inventory)
            .where(
                Inventory.character_id == character.id,
                Inventory.item_id == item.id,
            )
            .with_for_update()
        )

        if inventory:
            inventory.quantity += quantity
        else:
            session.add(Inventory(
                character_id=character.id,
                item_id=item.id,
                quantity=quantity,
            ))

    for contribution, character in rows:
        share = max(0, int(contribution.damage or 0)) / total_damage
        factor = 0.15 + 0.85 * share

        gold = min(2_000_000_000, int(rewards["gold"] * factor))
        xp = min(2_000_000_000, int(rewards["xp"] * factor))
        skill_xp = min(2_000_000_000, int(rewards["skill_xp"] * factor))
        gems = max(1, min(2_000_000_000, int(rewards["gems"] * factor)))

        old_gold = int(character.gold or 0)
        old_gems = int(character.gems or 0)
        old_skill_xp = int(character.skill_xp or 0)

        character.gold = min(2_147_483_647, old_gold + gold)
        character.gems = min(2_147_483_647, old_gems + gems)
        character.skill_xp = min(2_147_483_647, old_skill_xp + skill_xp)

        received_gold = character.gold - old_gold
        received_gems = character.gems - old_gems
        received_skill_xp = character.skill_xp - old_skill_xp
        received_xp = 0 if int(character.level or 1) >= 100 else xp

        drops = []

        if potions:
            potion_count = 10 if level >= 100 else 1
            for _ in range(potion_count):
                potion = random.choice(potions)
                await grant_item(character, potion)
                drops.append(potion.name)

        if level >= 100 and equipment:
            equipment_item = random.choice(equipment)
            await grant_item(character, equipment_item)
            drops.append(equipment_item.name)

        drop_text = ""
        if drops:
            counts = {}
            for item_name in drops:
                counts[item_name] = counts.get(item_name, 0) + 1
            drop_text = " و غنیمت: " + "، ".join(
                f"«{name}»" + (f" ×{count}" if count > 1 else "")
                for name, count in counts.items()
            )

        notices.append((
            character.telegram_id,
            received_xp,
            f"🏆 جایزه باس برای {character.name}: "
            f"+{received_gold:,} Gold، +{received_gems:,} Gem، "
            f"+{received_xp:,} XP، +{received_skill_xp:,} Skill XP"
            f"{drop_text}"
        ))

        report_rows.append((
            int(contribution.damage or 0),
            character.name,
            received_gold,
            received_gems,
            received_xp,
            received_skill_xp,
            drops,
            character.id == last_character_id,
        ))

    boss.status = "defeated"
    boss.hp = 0
    report_rows.sort(key=lambda row: row[0], reverse=True)

    report = [
        "╔═══ 📜 <b>تومار غنیمت و دلاوری</b> ═══╗",
        f"🐉 <b>نبرد با {html.escape(str(boss.name))}</b>",
        f"💥 مجموع آسیب قهرمانان: <b>{sum(row[0] for row in report_rows):,}</b>",
    ]

    if report_rows and report_rows[0][0] > 0:
        report.append(
            f"👑 بیشترین آسیب: <b>{html.escape(str(report_rows[0][1]))}</b> · "
            f"{report_rows[0][0]:,}"
        )

    for damage, name, gold, gems, xp, skill_xp, drops, last_hit in report_rows:
        item_text = ""
        if drops:
            counts = {}
            for item_name in drops:
                counts[item_name] = counts.get(item_name, 0) + 1
            item_text = " · غنیمت: " + "، ".join(
                f"{html.escape(str(item_name))}"
                + (f" ×{count}" if count > 1 else "")
                for item_name, count in counts.items()
            )

        last_text = " · ضربهٔ آخر" if last_hit else ""
        report.append(
            f"\n✦ <b>{html.escape(str(name))}</b>{last_text}"
            f"\n　⚔️ آسیب: {damage:,} · 🌟 XP: +{xp:,}"
            f"\n　💰 طلا: +{gold:,} · 💎 گوهر: +{gems:,}"
            f" · ✨ تجربهٔ مهارت: +{skill_xp:,}{item_text}"
        )

    report.append("\n╚══════ ✧ دفتر قهرمانان اِلدوریا ✧ ══════╝")
    return notices, "\n".join(report)


