async def boss_scheduler() -> None:
    """Spawn at most one live boss per group; due groups get a new boss hourly."""
    while True:
        try:
            # A group boss has exactly one hour to be defeated. Expired bosses
            # escape without rewards and the next hourly spawn becomes due.
            now = datetime.utcnow()
            expired_notices = []
            async with AsyncSessionLocal() as session:
                expired = list((await session.scalars(select(GroupBoss).where(
                    GroupBoss.status == "active",
                    GroupBoss.spawned_at.is_not(None),
                    GroupBoss.spawned_at <= now - timedelta(hours=1),
                ).limit(100))).all())
                for row in expired:
                    expired_notices.append((row.chat_id, row.message_id, row.name, row.chat_title))
                    await session.execute(delete(GroupBossContribution).where(GroupBossContribution.boss_id == row.id))
                    row.status = "waiting"
                    row.hp = 0
                    row.next_spawn_at = now
                    row.message_id = None
                if expired:
                    await session.commit()
            for expired_chat_id, expired_message_id, expired_name, expired_title in expired_notices:
                escaped_text = (f"🌫️ <b>{html.escape(expired_name)}</b> از این منطقه عبور کرد و کشته نشد.\n"
                                "⏳ مهلت یک‌ساعته تمام شد؛ هیچ غنیمتی به هیچ بازیکنی تعلق نگرفت.")
                announced = False
                if expired_message_id:
                    try:
                        await bot.edit_message_caption(chat_id=expired_chat_id, message_id=int(expired_message_id), caption=escaped_text, parse_mode="HTML")
                        announced = True
                    except Exception:
                        try:
                            await bot.edit_message_text(chat_id=expired_chat_id, message_id=int(expired_message_id), text=escaped_text, parse_mode="HTML")
                            announced = True
                        except Exception:
                            logger.debug("Could not update expired boss message", exc_info=True)
                if not announced:
                    try:
                        await bot.send_message(expired_chat_id, escaped_text, parse_mode="HTML")
                    except Exception:
                        logger.exception("Could not announce expired boss: chat_id=%s", expired_chat_id)

            async with AsyncSessionLocal() as session:
                due = list((await session.scalars(select(GroupBoss).where(
                    GroupBoss.status.in_(["waiting", "defeated"]),
                    GroupBoss.next_spawn_at <= datetime.utcnow(),
                ).limit(100))).all())
                due_data = [(r.id, r.chat_id, r.chat_title) for r in due]
            for row_id, chat_id, title in due_data:
                async with AsyncSessionLocal() as session:
                    row = await session.scalar(select(GroupBoss).where(GroupBoss.id == row_id).with_for_update())
                    if not row or row.status not in {"waiting", "defeated"} or row.next_spawn_at > datetime.utcnow():
                        continue
                    # Select while holding the group row lock, and avoid spawning
                    # the same boss twice in a row in this group.
                    previous_boss_key = row.boss_key if row.spawned_at is not None else None
                    cfg, spawned_level = choose_boss_spawn(previous_boss_key)
                    await session.execute(delete(GroupBossContribution).where(GroupBossContribution.boss_id == row.id))
                    row.boss_key, row.name = cfg["key"], cfg["name"]
                    row.boss_level = spawned_level
                    scaled = boss_level_stats(cfg, spawned_level)
                    row.max_hp = row.hp = scaled["hp"]
                    row.status = "active"
                    row.spawned_at = datetime.utcnow()
                    row.next_spawn_at = datetime.utcnow() + timedelta(hours=1)
                    row.message_id = None
                    await session.commit()
                caption = boss_spawn_caption(cfg, spawned_level, row.max_hp, boss_weakness(cfg))
                sent = None
                image_path = resolve_boss_image(cfg)
                try:
                    if image_path is not None:
                        from aiogram.types import FSInputFile
                        from utils.telegram_image_preview import prepare_telegram_image
                        preview_path = prepare_telegram_image(image_path)
                        sent = await bot.send_photo(chat_id, FSInputFile(str(preview_path)), caption=caption, parse_mode="HTML")
                    else:
                        sent = await bot.send_message(chat_id, caption, parse_mode="HTML")
                except Exception:
                    logger.exception("Could not announce group boss: chat_id=%s", chat_id)
                    async with AsyncSessionLocal() as session:
                        row = await session.scalar(select(GroupBoss).where(GroupBoss.id == row_id))
                        if row:
                            row.status = "waiting"
                            row.next_spawn_at = datetime.utcnow() + timedelta(minutes=5)
                            await session.commit()
                    continue
                async with AsyncSessionLocal() as session:
                    row = await session.scalar(select(GroupBoss).where(GroupBoss.id == row_id))
                    if row:
                        row.message_id = sent.message_id
                        await session.commit()
        except asyncio.CancelledError:
            raise
        except Exception:
            logger.exception("Group boss scheduler iteration failed")
        await asyncio.sleep(30)


