def choose_boss_spawn(previous_boss_key: str | None = None) -> tuple[dict, int]:
    """Choose from all 50 bosses and a weighted level from 1..200.

    Boss identities are equally likely (except that the immediately previous
    boss is avoided when alternatives exist). Boss levels are weighted toward
    the lower range without forcing every spawn to Lv.1.
    """
    candidates = [boss for boss in BOSS_POOL if boss["key"] != previous_boss_key]
    if not candidates:
        candidates = list(BOSS_POOL)
    cfg = random.choice(candidates)

    levels = list(range(1, 201))
    # A smooth distribution: low levels are common; high-level bosses remain
    # possible, but rare. The exponent is intentionally gentle so levels vary.
    weights = [1 / (level ** 0.72) for level in levels]
    level = random.choices(levels, weights=weights, k=1)[0]
    return cfg, level


def boss_level_stats(cfg: dict, level: int) -> dict[str, int]:
    """Scale boss combat stats and rewards from level 1 to level 200."""
    level = max(1, min(200, int(level or 1)))
    progress = (level - 1) / 199

    def reward(minimum: int, maximum: int) -> int:
        return round(minimum + progress * (maximum - minimum))

    return {
        "hp": max(1_500, int(cfg["hp"] * 3 * ((level / 100) ** 1.5))),
        "attack": max(8, int(cfg["attack"] * (level ** 1.5) / 5)),
        "gold": reward(3_000, 50_000),
        "xp": reward(500, 40_000),
        "skill_xp": reward(300, 30_000),
        "gems": reward(2, 40),
    }

ELEMENTS = {
    "fire": "🔥 آتش", "water": "💧 آب", "wind": "🌪️ باد",
    "earth": "🪨 خاک", "electro": "⚡ الکترو", "ice": "❄️ یخ",
    "light": "✨ نور", "dark": "🌑 تاریکی",
}

# Every boss has exactly one elemental weakness; stable by boss key.
def boss_weakness(cfg: dict) -> str:
    keys = [b["key"] for b in BOSS_POOL]
    elements = tuple(ELEMENTS)
    try:
        return elements[keys.index(cfg["key"]) % len(elements)]
    except (ValueError, KeyError):
        return "light"


