@router.callback_query(F.data.startswith("potion:use:"))
async def potion_consume_selected(cb: CallbackQuery):
    try:
        _, _, kind, inv_id_text = (cb.data or "").split(":", 3)
        inv_id = int(inv_id_text)
    except (ValueError, TypeError):
        await cb.answer("معجون انتخاب‌شده معتبر نیست.", show_alert=True); return
    if kind not in {"hp", "mana"} or cb.message is None:
        await cb.answer("انتخاب نامعتبر است.", show_alert=True); return
    mana = kind == "mana"
    from services.death_service import ensure_character_alive
    alive, alive_message = await ensure_character_alive(cb.from_user.id)
    if not alive or alive_message:
        await cb.answer(alive_message or "💀 قهرمانت از پا افتاده است.", show_alert=True); return
    try:
        from services.combat_service import has_active_battle
        # Block direct potion use only during adventure fights.
        # Boss and player-vs-player combat are allowed to use this command.
        if await has_active_battle(cb.from_user.id):
            await cb.answer("⚔️ از دکمهٔ معجون داخل پنل مبارزه استفاده کن تا محدودیت‌ها رعایت شوند.", show_alert=True); return
    except Exception:
        logger.exception("Could not verify active battle before potion consumption")
        await cb.answer("❌ وضعیت مبارزه بررسی نشد؛ مصرف لغو شد.", show_alert=True); return
    async with AsyncSessionLocal() as session:
        char = await session.scalar(select(Character).where(Character.telegram_id == cb.from_user.id).with_for_update())
        if char is None:
            await cb.answer("ابتدا /start را بزن و شخصیت بساز.", show_alert=True); return
        now = datetime.utcnow()
        if char.dead_until and now < char.dead_until:
            remaining = max(1, int((char.dead_until - now).total_seconds()))
            await cb.answer(f"💀 قهرمانت از پا افتاده است؛ {remaining // 60} دقیقه و {remaining % 60} ثانیه تا احیا.", show_alert=True); return
        if char.dead_until and now >= char.dead_until:
            char.dead_until = None
            char.hp = max(1, int(char.max_hp or 100))
            char.mana = max(1, int(char.max_mana or 100))
            await session.commit()
            await cb.answer("✨ قهرمان با HP و Mana کامل احیا شد؛ معجونی مصرف نشد.", show_alert=True); return
        inv = await session.scalar(select(Inventory).where(Inventory.id == inv_id, Inventory.character_id == char.id).with_for_update())
        if inv is None or inv.quantity <= 0:
            await cb.answer("این معجون دیگر در صندوقچه نیست.", show_alert=True); return
        item = await session.scalar(select(Item).where(Item.id == inv.item_id, Item.item_type == "potion"))
        if item is None:
            await cb.answer("آیتم انتخاب‌شده معجون معتبر نیست.", show_alert=True); return
        name = item.name.lower()
        if "سطح ۸۰" in name and int(char.level or 1) < 80:
            await cb.answer("این معجون از سطح ۸۰ به بالا قابل استفاده است.", show_alert=True); return
        kind = potion_kind(name)
        is_mana_item = kind == "mana"
        if kind is None or is_mana_item != mana:
            await cb.answer("این معجون برای نوار انتخاب‌شده مناسب نیست.", show_alert=True); return
        stats = await get_final_character_stats(cb.from_user.id)
        char.max_hp = max(1, int(stats.get("hp", char.max_hp or 100)))
        char.max_mana = max(1, int(stats.get("mana", char.max_mana or 100)))
        char.hp = min(int(char.hp or 0), int(char.max_hp))
        char.mana = min(int(char.mana or 0), int(char.max_mana))
        maximum = int(char.max_mana if mana else char.max_hp)
        current = int(char.mana if mana else char.hp)
        amount = int(maximum * potion_restore_ratio(name))
        try:
            from services.scroll_service import has_buff
            if await has_buff(cb.from_user.id, "mana" if mana else "healing"):
                amount = int(amount * 1.20)
        except Exception:
            logger.exception("Could not apply recovery scroll to potion")
        restored = min(max(0, maximum - current), max(0, amount))
        if restored <= 0:
            await cb.answer("نوار مربوطه از قبل پر است؛ معجون مصرف نشد.", show_alert=True); return
        if mana: char.mana = current + restored
        else: char.hp = current + restored
        inv.quantity -= 1
        if inv.quantity <= 0: await session.delete(inv)
        current_after = int(char.mana if mana else char.hp)
        hero_name = char.name
        item_name = item.name
        await session.commit()
    try:
        from services.combat_service import sync_character_vitals_to_battles
        from services.pvp_service import sync_character_vitals_to_pvp
        await sync_character_vitals_to_battles(cb.from_user.id, int(char.hp or 0), int(char.mana or 0))
        await sync_character_vitals_to_pvp(cb.from_user.id, int(char.hp or 0), int(char.mana or 0))
    except Exception:
        logger.exception("Could not refresh active battle caches after potion use")
    result = (f"🔷 قهرمان {html.escape(hero_name)} مانای خود را ریکاوری کرد: <b>+{restored} Mana</b>\nMana: {current_after}/{maximum}" if mana else f"🧪 قهرمان {html.escape(hero_name)} خود را شفا داد: <b>+{restored} HP</b>\nHP: {current_after}/{maximum}")
    await cb.answer(f"{item_name} مصرف شد؛ +{restored} {'Mana' if mana else 'HP'}")
    if cb.message.chat.type == "private":
        try:
            await cb.message.answer(result, parse_mode="HTML")
            from handlers.profile import show_profile
            await show_profile(cb)
            return
        except Exception:
            logger.exception("Could not refresh profile after potion recovery")
    try:
        await cb.message.edit_text(result, parse_mode="HTML", reply_markup=InlineKeyboardMarkup(inline_keyboard=[[InlineKeyboardButton(text="🔙 پروفایل", callback_data="menu:profile")]]))
    except Exception:
        await cb.message.answer(result, parse_mode="HTML")


